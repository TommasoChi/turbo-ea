from __future__ import annotations

import importlib.util
import json
from pathlib import Path

_GEN = Path(__file__).resolve().parents[3] / "scripts" / "archimate" / "generate_taxonomy.py"
_spec = importlib.util.spec_from_file_location("gen_taxonomy", _GEN)
gen = importlib.util.module_from_spec(_spec)
assert _spec and _spec.loader
_spec.loader.exec_module(gen)

MINI = Path(__file__).resolve().parents[1] / "fixtures" / "archimate" / "relationships_mini.xml"


def test_parse_keeps_letters_sorted_and_expands_junction_targets():
    table = gen.parse_archi_table(MINI)
    assert table["BusinessActor"]["BusinessProcess"] == "fiortv"
    assert table["BusinessActor"]["AndJunction"] == "fiot"
    assert table["BusinessActor"]["OrJunction"] == "fiot"
    assert table["BusinessActor"]["Relationship"] == "o"


def test_parse_expands_junction_sources():
    table = gen.parse_archi_table(MINI)
    assert table["AndJunction"]["BusinessActor"] == "ft"
    assert table["OrJunction"]["BusinessActor"] == "ft"
    assert "Junction" not in table


def test_render_json_has_provenance_and_is_deterministic():
    table = gen.parse_archi_table(MINI)
    a = gen.render_json(
        table, source="https://example.test/relationships.xml", ref="abc123", version="3.2"
    )
    b = gen.render_json(
        table, source="https://example.test/relationships.xml", ref="abc123", version="3.2"
    )
    assert a == b
    data = json.loads(a)
    assert data["_provenance"] == {
        "source": "https://example.test/relationships.xml",
        "ref": "abc123",
        "version": "3.2",
        "note": "Generated by scripts/archimate/generate_taxonomy.py - do not edit by hand.",
    }
    assert data["table"]["BusinessActor"]["BusinessProcess"] == "fiortv"


def test_render_ts_exports_the_table_and_a_header():
    table = gen.parse_archi_table(MINI)
    ts = gen.render_ts(table, source="s", ref="r", version="3.2")
    assert ts.startswith("// GENERATED by scripts/archimate/generate_taxonomy.py")
    assert "export const RELATION_TABLE: Record<string, Record<string, string>> = {" in ts
    assert '"BusinessProcess": "fiortv"' in ts
    assert "export const RELATION_TABLE_PROVENANCE" in ts


def test_unknown_letter_is_an_error():
    import pytest

    bad = Path(__file__).parent / "_bad_rel.xml"
    bad.write_text(
        '<relationships><source concept="A">'
        '<target concept="B" relations="z"/></source></relationships>'
    )
    try:
        with pytest.raises(ValueError, match="unknown relation letter"):
            gen.parse_archi_table(bad)
    finally:
        bad.unlink()
