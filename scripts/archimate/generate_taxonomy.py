"""Generate the ArchiMate relationship matrix from Archi's ``relationships.xml``.

Archi publishes the ArchiMate 3.2 relationship table (Appendix B) as XML. This
script reads a LOCAL copy and writes two derived artifacts: a JSON file for the
backend validator and a TypeScript file for the editor. Only the generated
output is committed; the provenance (URL, commit, version) goes in the header.

    python scripts/archimate/generate_taxonomy.py --archi-xml <path> --ref <git sha> \
        --source <url of the file at that sha>
"""

from __future__ import annotations

import argparse
import json
import xml.etree.ElementTree as ET  # trusted local input, not user data
from pathlib import Path

LETTERS = set("acfginorstv")
ROOT = Path(__file__).resolve().parents[2]
OUT_JSON = ROOT / "backend" / "app" / "services" / "archimate" / "relation_table.json"
OUT_TS = (
    ROOT / "frontend" / "src" / "features" / "archimate" / "taxonomy" / "relationTable.generated.ts"
)


def _expand(concept: str) -> list[str]:
    return ["AndJunction", "OrJunction"] if concept == "Junction" else [concept]


def parse_archi_table(path: Path) -> dict[str, dict[str, str]]:
    table: dict[str, dict[str, str]] = {}
    root = ET.parse(path).getroot()
    for src in root.findall("source"):
        for tgt in src.findall("target"):
            letters = "".join(sorted(tgt.get("relations", "")))
            bad = set(letters) - LETTERS
            if bad:
                raise ValueError(
                    f"unknown relation letter(s) {sorted(bad)} in "
                    f"{src.get('concept')}->{tgt.get('concept')}"
                )
            for s in _expand(src.get("concept", "")):
                for t in _expand(tgt.get("concept", "")):
                    table.setdefault(s, {})[t] = letters
    return {s: dict(sorted(t.items())) for s, t in sorted(table.items())}


def _provenance(source: str, ref: str, version: str) -> dict[str, str]:
    return {
        "source": source,
        "ref": ref,
        "version": version,
        "note": "Generated by scripts/archimate/generate_taxonomy.py - do not edit by hand.",
    }


def render_json(table: dict, *, source: str, ref: str, version: str) -> str:
    return (
        json.dumps(
            {"_provenance": _provenance(source, ref, version), "table": table},
            indent=1,
            ensure_ascii=False,
        )
        + "\n"
    )


def render_ts(table: dict, *, source: str, ref: str, version: str) -> str:
    prov = _provenance(source, ref, version)
    lines = [
        "// GENERATED by scripts/archimate/generate_taxonomy.py - do not edit by hand.",
        f"// Source: {source} @ {ref} (ArchiMate {version} relationship table).",
        "",
        "export const RELATION_TABLE_PROVENANCE = "
        + json.dumps(prov, ensure_ascii=False)
        + " as const;",
        "",
        "export const RELATION_TABLE: Record<string, Record<string, string>> = {",
    ]
    for s, targets in table.items():
        lines.append(f'  "{s}": {{')
        for t, letters in targets.items():
            lines.append(f'    "{t}": "{letters}",')
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--archi-xml", required=True, type=Path)
    ap.add_argument("--source", required=True)
    ap.add_argument("--ref", required=True)
    ap.add_argument("--version", default="3.2")
    a = ap.parse_args()
    table = parse_archi_table(a.archi_xml)
    OUT_JSON.write_text(
        render_json(table, source=a.source, ref=a.ref, version=a.version), encoding="utf-8"
    )
    OUT_TS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.write_text(
        render_ts(table, source=a.source, ref=a.ref, version=a.version), encoding="utf-8"
    )
    print(f"{sum(len(t) for t in table.values())} pairs from {len(table)} sources")


if __name__ == "__main__":
    main()
